/**
 * Generate full synthetic multi-GNSS ephemerides (32 GPS, 24 GLONASS, 30 Galileo, 35 BeiDou, 4 QZSS, 4 SBAS)
 * to demonstrate full global constellation rendering if RINEX file is partial!
 */
export function generateFullConstellationEphemerides(baseNavData) {
  const fullSats = [];

  const constellationsConfig = [
    { prefix: 'G', name: 'GPS', count: 32, alt: 20200000, inc: 55, planes: 6 },
    { prefix: 'R', name: 'GLONASS', count: 24, alt: 19100000, inc: 64.8, planes: 3 },
    { prefix: 'E', name: 'Galileo', count: 30, alt: 23222000, inc: 56, planes: 3 },
    { prefix: 'C', name: 'BeiDou', count: 35, alt: 21528000, inc: 55, planes: 3 },
    { prefix: 'J', name: 'QZSS', count: 4, alt: 35786000, inc: 43, planes: 1 },
    { prefix: 'S', name: 'SBAS', count: 6, alt: 35786000, inc: 0.1, planes: 1 }
  ];

  const baseDate = (baseNavData && baseNavData.satellites && baseNavData.satellites.length > 0)
    ? baseNavData.satellites[0].epoch
    : new Date();

  for (const cfg of constellationsConfig) {
    const planeSize = Math.ceil(cfg.count / cfg.planes);

    for (let i = 1; i <= cfg.count; i++) {
      const prnNum = i < 10 ? '0' + i : '' + i;
      const prn = cfg.prefix + prnNum;

      // Calculate realistic Keplerian orbital parameters
      const planeIdx = Math.floor((i - 1) / planeSize);
      const satInPlaneIdx = (i - 1) % planeSize;

      const semiMajorAxis = 6378137.0 + cfg.alt; // meters
      const sqrtA = Math.sqrt(semiMajorAxis);

      const omega0 = (planeIdx * (360 / cfg.planes)) * (Math.PI / 180);
      const m0 = (satInPlaneIdx * (360 / planeSize)) * (Math.PI / 180);
      const i0 = cfg.inc * (Math.PI / 180);

      // Add a degraded satellite to test health indicators (e.g. G11, E18, C05)
      const isDegraded = (prn === 'G11' || prn === 'E18' || prn === 'C05');
      const svHealth = isDegraded ? 1 : 0;

      fullSats.push({
        prn,
        constellation: cfg.name,
        epoch: baseDate,
        af0: 0.0001 * (i % 5),
        af1: 1e-12,
        af2: 0,
        iode: 12,
        crs: 10 + i,
        deltaN: 4.2e-9,
        m0,
        cuc: 1e-6,
        e: cfg.name === 'QZSS' ? 0.075 : 0.001,
        cus: 2e-6,
        sqrtA,
        toe: 43200,
        cic: 1e-6,
        omega0,
        cis: 1e-6,
        i0,
        crc: 20 + i,
        omega: (i * 30) * (Math.PI / 180),
        omegaDot: -2.6e-9,
        idot: -1e-10,
        codesL2: 1,
        gpsWeek: 2380,
        l2PFlag: 0,
        svAccuracy: 2.0,
        svHealth,
        isHealthy: !isDegraded,
        healthText: isDegraded ? 'Degraded / Unhealthy (Code 1)' : 'Healthy',
        tgd: -1.8e-8,
        iodc: 12,
        transmissionTime: 43200
      });
    }
  }

  return fullSats;
}
